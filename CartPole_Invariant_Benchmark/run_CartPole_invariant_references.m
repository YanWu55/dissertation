%% Cart-Pole Controlled Lyapunov Invariant-Set Reference Generation
%
% Benchmark:
%   A.6.4 Controlled Lyapunov Invariant-Set Certification
%
% State:
%   x = [p; v; theta; omega]
%
% theta = 0 corresponds to the upright equilibrium.
%
% Fixed nonlinear plant:
%   M = 1.0 kg
%   m = 0.1 kg
%   l = 0.5 m
%   g = 9.81 m/s^2
%
% Fixed controller:
%   continuous-time LQR
%
% Q = diag([10 1 150 5])
% R = 0.2
%
% Applied control:
%   u = clip(-K*x, -10, 10)
%
% State constraint:
%   |p| <= 2.4 m
%
% Candidate Lyapunov sublevel sets:
%   Baseline      rho = 0.25
%   Intermediate  rho = 0.60
%   Challenge     rho = 1.00
%
% Reference logic:
%
%   V(x) = x'*P*x
%
% For each rho:
%   1. sample the complete ellipsoid boundary numerically;
%   2. search for max nonlinear Vdot using multi-start fmincon;
%   3. compute exact ellipsoidal bounds on |p| and |-Kx|;
%   4. propagate independent nonlinear boundary trajectories;
%   5. record whether the candidate set passes the adopted
%      numerical certification criteria.
%
% IMPORTANT:
% This is a high-accuracy numerical certification/reference
% procedure, not a formal interval-arithmetic proof.


clear;
clc;
close all;


%% ============================================================
% 0. Check required MATLAB functions
% =============================================================

if isempty(which('lqr'))

    error(['MATLAB lqr() cannot be found. ' ...
           'Control System Toolbox is required.']);

end


if isempty(which('fmincon'))

    error(['MATLAB fmincon() cannot be found. ' ...
           'Optimization Toolbox is required.']);

end


fprintf('MATLAB version: %s\n', version);
fprintf('Computer platform: %s\n', computer);


%% ============================================================
% 1. Output folder
% =============================================================

outputFolder = ...
    'CartPole_Invariant_References';


if ~exist(outputFolder,'dir')
    mkdir(outputFolder);
end


%% ============================================================
% 2. Fixed Cart-Pole parameters
% =============================================================

M = 1.0;       % cart mass [kg]
m = 0.1;       % pole mass [kg]
l = 0.5;       % pole length [m]
g = 9.81;      % gravity [m/s^2]


% Constraints
uMax = 10.0;           % N
pMax = 2.4;            % m


fprintf('\n');
fprintf('=============================================\n');
fprintf('Cart-Pole Controlled Invariant-Set Benchmark\n');
fprintf('=============================================\n');

fprintf('M = %.6f kg\n', M);
fprintf('m = %.6f kg\n', m);
fprintf('l = %.6f m\n', l);
fprintf('g = %.6f m/s^2\n', g);

fprintf('Force constraint: |u| <= %.3f N\n', uMax);
fprintf('Position constraint: |p| <= %.3f m\n', pMax);


%% ============================================================
% 3. Linearisation about upright equilibrium
%
% State ordering:
%   [p v theta omega]'
%
% theta = 0 upright
% =============================================================

A = [ ...
    0, 1, 0, 0; ...
    0, 0, -(m*g/M), 0; ...
    0, 0, 0, 1; ...
    0, 0, ((M+m)*g/(M*l)), 0];


B = [ ...
    0; ...
    1/M; ...
    0; ...
    -1/(M*l)];


%% ============================================================
% 4. Fixed LQR specification
% =============================================================

Q = diag([ ...
    10, ...
     1, ...
   150, ...
     5]);


R = 0.2;


[K,P,closedLoopEigenvalues] = ...
    lqr(A,B,Q,R);


Acl = A - B*K;


isHurwitz = ...
    all(real(closedLoopEigenvalues) < 0);


fprintf('\n');
fprintf('=============================================\n');
fprintf('Fixed LQR Reference Controller\n');
fprintf('=============================================\n');

fprintf('\nK =\n');
disp(K);

fprintf('P =\n');
disp(P);

fprintf('Closed-loop eigenvalues:\n');
disp(closedLoopEigenvalues);

fprintf('A-BK Hurwitz: %d\n', ...
    isHurwitz);


if ~isHurwitz

    error('The prescribed LQR closed loop is not Hurwitz.');

end


%% ============================================================
% 5. CARE numerical consistency check
% =============================================================

careResidual = ...
    A'*P + ...
    P*A - ...
    P*B*(R\(B'*P)) + ...
    Q;


careResidualNorm = ...
    norm(careResidual,'fro');


fprintf('CARE residual Frobenius norm: %.6e\n', ...
    careResidualNorm);


%% ============================================================
% 6. Positive definiteness of P
% =============================================================

P = 0.5*(P + P');


pEigenvalues = eig(P);


if any(pEigenvalues <= 0)

    error('The LQR matrix P is not positive definite.');

end


fprintf('Minimum eigenvalue of P: %.6e\n', ...
    min(pEigenvalues));


%% ============================================================
% 7. Candidate invariant-set levels
% =============================================================

cases(1).label = 'B';
cases(1).difficulty = 'Baseline';
cases(1).rho = 0.25;

cases(2).label = 'I';
cases(2).difficulty = 'Intermediate';
cases(2).rho = 0.60;

cases(3).label = 'C';
cases(3).difficulty = 'Challenge';
cases(3).rho = 1.00;


%% ============================================================
% 8. Numerical boundary-search settings
% =============================================================

% Large fixed random boundary sample used to search globally
% before local refinement.
numberBoundarySamples = 30000;


% Number of highest-Vdot sampled points supplied to fmincon.
numberOptimisationStarts = 20;


% Fixed random seed for reproducibility.
rng(2026,'twister');


% Numerical certification tolerance.
%
% We require the largest identified boundary Vdot to be strictly
% negative by more than this tolerance.
vdotTolerance = 1e-8;


% Constraint tolerance used for fmincon.
optimOptions = optimoptions( ...
    'fmincon', ...
    'Algorithm','sqp', ...
    'Display','none', ...
    'MaxIterations',500, ...
    'MaxFunctionEvaluations',50000, ...
    'ConstraintTolerance',1e-10, ...
    'OptimalityTolerance',1e-10, ...
    'StepTolerance',1e-12);


%% ============================================================
% 9. Independent nonlinear trajectory-validation settings
% =============================================================

numberRandomValidationTrajectories = 100;


% Five extra critical boundary states are later added:
%
%   worst-Vdot state
%   +max-force direction
%   -max-force direction
%   +max-position direction
%   -max-position direction
%
numberCriticalTrajectories = 5;


numberValidationTrajectories = ...
    numberRandomValidationTrajectories + ...
    numberCriticalTrajectories;


validationHorizon = 5.0;     % s

validationOutputStep = 0.005;


tEval = ...
    (0:validationOutputStep:validationHorizon)';


validationRelTol = 1e-10;
validationAbsTol = 1e-12;
validationMaxStep = 0.005;


odeOptions = odeset( ...
    'RelTol',validationRelTol, ...
    'AbsTol',validationAbsTol, ...
    'MaxStep',validationMaxStep);


% Numerical tolerance for trajectory V <= rho check.
trajectoryVTolerance = 1e-7;


%% ============================================================
% 10. Useful ellipsoid transformations
% =============================================================

Pinv = inv(P);


% Symmetric inverse square root P^(-1/2)
[VP,DP] = eig(P);

PinvHalf = ...
    VP * ...
    diag(1 ./ sqrt(diag(DP))) * ...
    VP';


%% ============================================================
% 11. Save common controller reference
% =============================================================

controllerMetadata.system = ...
    'Cart-Pole';

controllerMetadata.task = ...
    'Controlled Invariant-Set Analysis';

controllerMetadata.controller = ...
    'Fixed continuous-time LQR';

controllerMetadata.stateOrder = ...
    'p v theta omega';

controllerMetadata.angleConvention = ...
    'theta = 0 is upright';

controllerMetadata.Q = Q;
controllerMetadata.R = R;
controllerMetadata.K = K;
controllerMetadata.P = P;

controllerMetadata.closedLoopEigenvalues = ...
    closedLoopEigenvalues;

controllerMetadata.isHurwitz = ...
    isHurwitz;

controllerMetadata.careResidualNorm = ...
    careResidualNorm;

controllerMetadata.matlabVersion = ...
    version;

controllerMetadata.computer = ...
    computer;

controllerMetadata.dateGenerated = ...
    char(datetime('now'));


save( ...
    fullfile( ...
        outputFolder, ...
        'CARTPOLE_INV_controller_reference.mat'), ...
    'A', ...
    'B', ...
    'Q', ...
    'R', ...
    'K', ...
    'P', ...
    'Acl', ...
    'closedLoopEigenvalues', ...
    'controllerMetadata');


%% ============================================================
% 12. Summary arrays
% =============================================================

summaryDifficulty = strings(3,1);

summaryRho = zeros(3,1);

summaryCertified = false(3,1);

summaryMaxVdot = zeros(3,1);

summaryMaxForce = zeros(3,1);

summaryForceMargin = zeros(3,1);

summaryMaxPosition = zeros(3,1);

summaryPositionMargin = zeros(3,1);

summaryMaxThetaDeg = zeros(3,1);

summaryTrajectoryPass = false(3,1);

summaryMaxTrajectoryVExcess = zeros(3,1);

summaryComputationTime = zeros(3,1);


%% ============================================================
% 13. Run B / I / C candidate-set checks
% =============================================================

for kCase = 1:length(cases)

    label = ...
        cases(kCase).label;

    difficulty = ...
        cases(kCase).difficulty;

    rho = ...
        cases(kCase).rho;


    fprintf('\n');
    fprintf('=============================================\n');
    fprintf('Running Cart-Pole Invariant Set: %s\n', ...
        difficulty);

    fprintf('rho = %.6f\n',rho);
    fprintf('=============================================\n');


    caseTimer = tic;


    %% --------------------------------------------------------
    % 13.1 Exact ellipsoidal component bounds
    %
    % For x' P x <= rho:
    %
    % max |c'x| =
    % sqrt(rho * c' * inv(P) * c)
    % ---------------------------------------------------------

    ePosition = [1;0;0;0];

    eTheta = [0;0;1;0];


    maxPositionExact = ...
        sqrt( ...
            rho * ...
            (ePosition' * Pinv * ePosition));


    maxThetaExact = ...
        sqrt( ...
            rho * ...
            (eTheta' * Pinv * eTheta));


    maxThetaDeg = ...
        rad2deg(maxThetaExact);


    % Unsaturated LQR command:
    % u_unsat = -K*x
    maxUnsaturatedForceExact = ...
        sqrt( ...
            rho * ...
            (K * Pinv * K'));


    forceMargin = ...
        uMax - ...
        maxUnsaturatedForceExact;


    positionMargin = ...
        pMax - ...
        maxPositionExact;


    noSaturationThroughoutSet = ...
        maxUnsaturatedForceExact <= ...
        uMax + 1e-10;


    positionConstraintThroughoutSet = ...
        maxPositionExact <= ...
        pMax + 1e-10;


    fprintf('\nExact ellipsoidal bounds:\n');

    fprintf('max |p|       = %.9f m\n', ...
        maxPositionExact);

    fprintf('position margin = %.9f m\n', ...
        positionMargin);

    fprintf('max |theta|   = %.9f deg\n', ...
        maxThetaDeg);

    fprintf('max |-Kx|     = %.9f N\n', ...
        maxUnsaturatedForceExact);

    fprintf('force margin  = %.9f N\n', ...
        forceMargin);

    fprintf('No saturation anywhere in Omega_rho: %d\n', ...
        noSaturationThroughoutSet);


    %% --------------------------------------------------------
    % 13.2 Generate a high-resolution boundary sample
    %
    % If z lies on the unit 4-sphere:
    %
    % x = sqrt(rho) * P^(-1/2) * z
    %
    % satisfies x' P x = rho.
    % ---------------------------------------------------------

    Z = randn( ...
        4, ...
        numberBoundarySamples);


    Z = ...
        Z ./ ...
        vecnorm(Z,2,1);


    Xboundary = ...
        sqrt(rho) * ...
        PinvHalf * ...
        Z;


    sampledVdot = ...
        zeros(numberBoundarySamples,1);


    sampledUnsaturatedForce = ...
        zeros(numberBoundarySamples,1);


    sampledAppliedForce = ...
        zeros(numberBoundarySamples,1);


    for j = 1:numberBoundarySamples

        xj = ...
            Xboundary(:,j);


        [vdot_j, ...
         uApplied_j, ...
         uUnsaturated_j] = ...
            localVdot( ...
                xj, ...
                P, ...
                K, ...
                uMax, ...
                M, ...
                m, ...
                l, ...
                g);


        sampledVdot(j) = ...
            vdot_j;

        sampledAppliedForce(j) = ...
            uApplied_j;

        sampledUnsaturatedForce(j) = ...
            uUnsaturated_j;

    end


    [maxSampledVdot, ...
     maxSampledIndex] = ...
        max(sampledVdot);


    xWorstSample = ...
        Xboundary(:,maxSampledIndex);


    fprintf('\nBoundary sampling:\n');

    fprintf('Boundary samples: %d\n', ...
        numberBoundarySamples);

    fprintf('Largest sampled Vdot: %.12e\n', ...
        maxSampledVdot);


    %% --------------------------------------------------------
    % 13.3 Select highest-Vdot samples for local optimisation
    % ---------------------------------------------------------

    [~,sortIndex] = ...
        sort(sampledVdot,'descend');


    optimisationStartIndices = ...
        sortIndex( ...
        1:min( ...
            numberOptimisationStarts, ...
            numberBoundarySamples));


    %% --------------------------------------------------------
    % 13.4 Boundary variable limits for fmincon
    %
    % Exact axis-aligned ellipsoid bounds improve numerical
    % conditioning without changing the ellipsoid constraint.
    % ---------------------------------------------------------

    componentBounds = ...
        sqrt( ...
            rho * ...
            diag(Pinv));


    lbOpt = ...
        -componentBounds;

    ubOpt = ...
         componentBounds;


    nonlinearBoundaryConstraint = ...
        @(x) localEllipsoidBoundaryConstraint( ...
            x, ...
            P, ...
            rho);


    objective = ...
        @(x) -localVdotOnly( ...
            x, ...
            P, ...
            K, ...
            uMax, ...
            M, ...
            m, ...
            l, ...
            g);


    %% --------------------------------------------------------
    % 13.5 Multi-start nonlinear maximisation of Vdot
    % ---------------------------------------------------------

    bestOptimisedVdot = ...
        -inf;

    xWorstOptimised = ...
        xWorstSample;

    optimisationResults = ...
        struct([]);


    for kStart = 1:length(optimisationStartIndices)

        xStart = ...
            Xboundary( ...
                :, ...
                optimisationStartIndices(kStart));


        try

            [xCandidate, ...
             objectiveCandidate, ...
             exitFlagCandidate, ...
             outputCandidate] = ...
                fmincon( ...
                    objective, ...
                    xStart, ...
                    [], ...
                    [], ...
                    [], ...
                    [], ...
                    lbOpt, ...
                    ubOpt, ...
                    nonlinearBoundaryConstraint, ...
                    optimOptions);


            candidateVdot = ...
                -objectiveCandidate;


            boundaryResidual = ...
                abs( ...
                    xCandidate' * ...
                    P * ...
                    xCandidate - ...
                    rho);


            optimisationResults(kStart).x = ...
                xCandidate;

            optimisationResults(kStart).Vdot = ...
                candidateVdot;

            optimisationResults(kStart).exitFlag = ...
                exitFlagCandidate;

            optimisationResults(kStart).output = ...
                outputCandidate;

            optimisationResults(kStart).boundaryResidual = ...
                boundaryResidual;


            if boundaryResidual <= 1e-7 && ...
                    candidateVdot > bestOptimisedVdot

                bestOptimisedVdot = ...
                    candidateVdot;

                xWorstOptimised = ...
                    xCandidate;

            end


        catch ME

            optimisationResults(kStart).x = [];
            optimisationResults(kStart).Vdot = NaN;
            optimisationResults(kStart).exitFlag = NaN;
            optimisationResults(kStart).output = [];
            optimisationResults(kStart).boundaryResidual = NaN;
            optimisationResults(kStart).errorMessage = ...
                ME.message;

        end

    end


    %% --------------------------------------------------------
    % 13.6 Conservative numerical reference maximum
    %
    % Use the larger of:
    %   - direct dense boundary sample
    %   - local optimisation results
    % ---------------------------------------------------------

    if isfinite(bestOptimisedVdot) && ...
            bestOptimisedVdot > maxSampledVdot

        maxBoundaryVdot = ...
            bestOptimisedVdot;

        xWorstVdot = ...
            xWorstOptimised;

        maxVdotSource = ...
            'fmincon refinement';

    else

        maxBoundaryVdot = ...
            maxSampledVdot;

        xWorstVdot = ...
            xWorstSample;

        maxVdotSource = ...
            'dense boundary sampling';

    end


    fprintf('\nBoundary optimisation:\n');

    fprintf('Maximum identified Vdot: %.12e\n', ...
        maxBoundaryVdot);

    fprintf('Maximum source: %s\n', ...
        maxVdotSource);

    fprintf('Worst boundary state:\n');
    disp(xWorstVdot');


    vdotConditionSatisfied = ...
        maxBoundaryVdot < ...
        -vdotTolerance;


    %% --------------------------------------------------------
    % 13.7 Construct critical deterministic boundary states
    % ---------------------------------------------------------

    % Maximum positive force-command direction
    forceDenominator = ...
        sqrt(K*Pinv*K');


    xForcePositive = ...
        sqrt(rho) * ...
        Pinv * ...
        K' / ...
        forceDenominator;


    xForceNegative = ...
        -xForcePositive;


    % Maximum positive cart-position direction
    positionDenominator = ...
        sqrt( ...
            ePosition' * ...
            Pinv * ...
            ePosition);


    xPositionPositive = ...
        sqrt(rho) * ...
        Pinv * ...
        ePosition / ...
        positionDenominator;


    xPositionNegative = ...
        -xPositionPositive;


    %% --------------------------------------------------------
    % 13.8 Independent boundary trajectory initial states
    % ---------------------------------------------------------

    Zvalidation = ...
        randn( ...
            4, ...
            numberRandomValidationTrajectories);


    Zvalidation = ...
        Zvalidation ./ ...
        vecnorm(Zvalidation,2,1);


    X0Validation = ...
        sqrt(rho) * ...
        PinvHalf * ...
        Zvalidation;


    X0Validation = [ ...
        X0Validation, ...
        xWorstVdot, ...
        xForcePositive, ...
        xForceNegative, ...
        xPositionPositive, ...
        xPositionNegative];


    %% --------------------------------------------------------
    % 13.9 Nonlinear trajectory validation
    % ---------------------------------------------------------

    validationTrajectories = ...
        cell(numberValidationTrajectories,1);


    trajectoryPassFlags = ...
        false(numberValidationTrajectories,1);


    trajectoryMaxV = ...
        zeros(numberValidationTrajectories,1);


    trajectoryMaxPosition = ...
        zeros(numberValidationTrajectories,1);


    trajectoryMaxAppliedForce = ...
        zeros(numberValidationTrajectories,1);


    trajectoryMaxUnsaturatedForce = ...
        zeros(numberValidationTrajectories,1);


    closedLoopODE = ...
        @(t,x) localClosedLoopDynamics( ...
            x, ...
            K, ...
            uMax, ...
            M, ...
            m, ...
            l, ...
            g);


    fprintf('\n');
    fprintf('Running %d nonlinear boundary trajectories...\n', ...
        numberValidationTrajectories);


    for j = 1:numberValidationTrajectories

        x0 = ...
            X0Validation(:,j);


        [tTrajectory,xTrajectory] = ...
            ode113( ...
                closedLoopODE, ...
                tEval, ...
                x0, ...
                odeOptions);


        numberSamples = ...
            size(xTrajectory,1);


        Vtrajectory = ...
            zeros(numberSamples,1);


        appliedForceTrajectory = ...
            zeros(numberSamples,1);


        unsaturatedForceTrajectory = ...
            zeros(numberSamples,1);


        for q = 1:numberSamples

            xq = ...
                xTrajectory(q,:)';


            Vtrajectory(q) = ...
                xq' * P * xq;


            [uApplied_q,uUnsaturated_q] = ...
                localController( ...
                    xq, ...
                    K, ...
                    uMax);


            appliedForceTrajectory(q) = ...
                uApplied_q;

            unsaturatedForceTrajectory(q) = ...
                uUnsaturated_q;

        end


        maxV_j = ...
            max(Vtrajectory);


        maxPosition_j = ...
            max(abs(xTrajectory(:,1)));


        maxAppliedForce_j = ...
            max(abs(appliedForceTrajectory));


        maxUnsaturatedForce_j = ...
            max(abs(unsaturatedForceTrajectory));


        trajectoryPass_j = ...
            maxV_j <= rho + trajectoryVTolerance && ...
            maxPosition_j <= pMax + 1e-9 && ...
            maxAppliedForce_j <= uMax + 1e-9;


        validationTrajectories{j}.t = ...
            tTrajectory;

        validationTrajectories{j}.x = ...
            xTrajectory;

        validationTrajectories{j}.V = ...
            Vtrajectory;

        validationTrajectories{j}.uApplied = ...
            appliedForceTrajectory;

        validationTrajectories{j}.uUnsaturated = ...
            unsaturatedForceTrajectory;


        trajectoryPassFlags(j) = ...
            trajectoryPass_j;

        trajectoryMaxV(j) = ...
            maxV_j;

        trajectoryMaxPosition(j) = ...
            maxPosition_j;

        trajectoryMaxAppliedForce(j) = ...
            maxAppliedForce_j;

        trajectoryMaxUnsaturatedForce(j) = ...
            maxUnsaturatedForce_j;

    end


    allTrajectoryChecksPassed = ...
        all(trajectoryPassFlags);


    maxTrajectoryV = ...
        max(trajectoryMaxV);


    maxTrajectoryVExcess = ...
        maxTrajectoryV - ...
        rho;


    maxTrajectoryPosition = ...
        max(trajectoryMaxPosition);


    maxTrajectoryAppliedForce = ...
        max(trajectoryMaxAppliedForce);


    maxTrajectoryUnsaturatedForce = ...
        max(trajectoryMaxUnsaturatedForce);


    fprintf('Trajectory checks passed: %d\n', ...
        allTrajectoryChecksPassed);

    fprintf('Maximum trajectory V-rho: %.12e\n', ...
        maxTrajectoryVExcess);

    fprintf('Maximum trajectory |p|: %.9f m\n', ...
        maxTrajectoryPosition);

    fprintf('Maximum trajectory applied |u|: %.9f N\n', ...
        maxTrajectoryAppliedForce);


    %% --------------------------------------------------------
    % 13.10 Overall adopted numerical certification result
    %
    % Requirements:
    %
    % 1. max boundary Vdot < -tolerance
    % 2. complete ellipsoid lies inside cart-position constraint
    % 3. unsaturated LQR command is inside force constraint over
    %    the complete ellipsoid
    % 4. all independent boundary trajectories pass
    % ---------------------------------------------------------

    referenceCertified = ...
        vdotConditionSatisfied && ...
        positionConstraintThroughoutSet && ...
        noSaturationThroughoutSet && ...
        allTrajectoryChecksPassed;


    computationTime = ...
        toc(caseTimer);


    fprintf('\n');
    fprintf('=============================================\n');
    fprintf('REFERENCE RESULT: %s\n',difficulty);
    fprintf('=============================================\n');

    fprintf('rho: %.6f\n',rho);

    fprintf('Maximum identified boundary Vdot: %.12e\n', ...
        maxBoundaryVdot);

    fprintf('Vdot condition satisfied: %d\n', ...
        vdotConditionSatisfied);

    fprintf('Maximum ellipsoidal |p|: %.9f m\n', ...
        maxPositionExact);

    fprintf('Position margin: %.9f m\n', ...
        positionMargin);

    fprintf('Maximum ellipsoidal |-Kx|: %.9f N\n', ...
        maxUnsaturatedForceExact);

    fprintf('Force margin: %.9f N\n', ...
        forceMargin);

    fprintf('All trajectory checks passed: %d\n', ...
        allTrajectoryChecksPassed);

    fprintf('Reference certified: %d\n', ...
        referenceCertified);

    fprintf('Computation time: %.6f s\n', ...
        computationTime);


    %% ========================================================
    % 14. Metadata
    % =========================================================

    metadata.system = ...
        'Cart-Pole';

    metadata.task = ...
        'Controlled Invariant-Set Analysis';

    metadata.benchmarkFamily = ...
        'Controlled Lyapunov Invariant-Set Certification';

    metadata.difficulty = ...
        difficulty;

    metadata.rho = ...
        rho;

    metadata.referenceType = ...
        'Analytical + Numerical';

    metadata.referenceInterpretation = ...
        ['Quadratic Lyapunov structure from LQR with ' ...
         'high-accuracy numerical nonlinear boundary search ' ...
         'and trajectory validation. Not a formal ' ...
         'interval-arithmetic proof.'];

    metadata.cartMass_kg = M;
    metadata.poleMass_kg = m;
    metadata.poleLength_m = l;
    metadata.gravity_mps2 = g;

    metadata.forceLimit_N = ...
        uMax;

    metadata.cartPositionLimit_m = ...
        pMax;

    metadata.Q = Q;
    metadata.R = R;
    metadata.K = K;
    metadata.P = P;

    metadata.closedLoopEigenvalues = ...
        closedLoopEigenvalues;

    metadata.careResidualNorm = ...
        careResidualNorm;

    metadata.numberBoundarySamples = ...
        numberBoundarySamples;

    metadata.numberOptimisationStarts = ...
        numberOptimisationStarts;

    metadata.vdotTolerance = ...
        vdotTolerance;

    metadata.maximumBoundaryVdot = ...
        maxBoundaryVdot;

    metadata.maximumVdotSource = ...
        maxVdotSource;

    metadata.worstVdotState = ...
        xWorstVdot;

    metadata.maximumPositionExact_m = ...
        maxPositionExact;

    metadata.positionMargin_m = ...
        positionMargin;

    metadata.maximumThetaExact_deg = ...
        maxThetaDeg;

    metadata.maximumUnsaturatedForceExact_N = ...
        maxUnsaturatedForceExact;

