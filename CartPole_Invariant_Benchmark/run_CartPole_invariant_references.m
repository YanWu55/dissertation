% LOCAL FUNCTION 1
% Nonlinear Cart-Pole dynamics
% =============================================================

function dx = localPlantDynamics( ...
    x, ...
    u, ...
    M, ...
    m, ...
    l, ...
    g)


    v = x(2);

    theta = x(3);

    omega = x(4);


    sinTheta = ...
        sin(theta);

    cosTheta = ...
        cos(theta);


    denominator = ...
        M + ...
        m*sinTheta^2;


    vDot = ...
        ( ...
        u ...
        - m*g*sinTheta*cosTheta ...
        + m*l*omega^2*sinTheta ...
        ) ...
        / denominator;


    omegaDot = ...
        ( ...
        g*sinTheta ...
        - vDot*cosTheta ...
        ) ...
        / l;


    dx = [ ...
        v; ...
        vDot; ...
        omega; ...
        omegaDot];

end


%% ============================================================
% LOCAL FUNCTION 2
% Saturated fixed LQR controller
% =============================================================

function [uApplied,uUnsaturated] = ...
    localController( ...
        x, ...
        K, ...
        uMax)


    uUnsaturated = ...
        -K*x;


    uApplied = ...
        min( ...
            max( ...
                uUnsaturated, ...
                -uMax), ...
            uMax);

end


%% ============================================================
% LOCAL FUNCTION 3
% Closed-loop nonlinear dynamics
% =============================================================

function dx = localClosedLoopDynamics( ...
    x, ...
    K, ...
    uMax, ...
    M, ...
    m, ...
    l, ...
    g)


    [uApplied,~] = ...
        localController( ...
            x, ...
            K, ...
            uMax);


    dx = ...
        localPlantDynamics( ...
            x, ...
            uApplied, ...
            M, ...
            m, ...
            l, ...
            g);

end


%% ============================================================
% LOCAL FUNCTION 4
% Lyapunov derivative
% =============================================================

function [Vdot,uApplied,uUnsaturated] = ...
    localVdot( ...
        x, ...
        P, ...
        K, ...
        uMax, ...
        M, ...
        m, ...
        l, ...
        g)


    [uApplied,uUnsaturated] = ...
        localController( ...
            x, ...
            K, ...
            uMax);


    dx = ...
        localPlantDynamics( ...
            x, ...
            uApplied, ...
            M, ...
            m, ...
            l, ...
            g);


    Vdot = ...
        2*x'*P*dx;

end


